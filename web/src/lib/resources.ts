export function resolveDefault(f: FieldDef, ctx: { projectId?: string } = {}): unknown {
  return typeof f.default === 'function' ? (f.default as (c: { projectId?: string }) => unknown)(ctx) : f.default;
}

/** Initial values for a new record */
export function newRecord(fields: FieldDef[], ctx: { projectId?: string } = {}): Row {
  const r: Row = {};
  for (const f of fields) {
    const d = resolveDefault(f, ctx);
    if (d !== undefined) r[f.name] = d;
    else if (f.type === 'checkbox') r[f.name] = false;
  }
  if (ctx.projectId && fields.some((f) => f.name === 'project_id')) r.project_id = ctx.projectId;
  return r;
}

/** Client-side validation (the database re-checks everything). Returns field → i18n error key. */
export function validate(fields: FieldDef[], row: Row): Record<string, string> {
  const errors: Record<string, string> = {};
  for (const f of fields) {
    const v = row[f.name];
    const empty = v === undefined || v === null || (typeof v === 'string' && v.trim() === '');
    if (f.required && empty) { errors[f.name] = 'v.required'; continue; }
    if (empty) continue;
    if (['number', 'money', 'percent'].includes(f.type)) {
      const n = Number(v);
      if (!Number.isFinite(n)) errors[f.name] = 'v.number';
      else if (f.min !== undefined && n < f.min) errors[f.name] = 'v.min';
      else if (f.max !== undefined && n > f.max) errors[f.name] = 'v.max';
    }
    if (f.type === 'email' && typeof v === 'string' && !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(v)) errors[f.name] = 'v.email';
    if (f.type === 'date' && typeof v === 'string' && !/^\d{4}-\d{2}-\d{2}$/.test(v)) errors[f.name] = 'v.date';
  }
  return errors;
}

/** Strip UI-only keys and convert empty strings to null before saving. */
export function toPayload(fields: FieldDef[], row: Row, isNew: boolean): Row {
  const out: Row = {};
  for (const f of fields) {
    if (f.readOnly) continue;
    if (!isNew && f.createOnly) continue;
    if (!(f.name in row)) continue;
    let v = row[f.name];
    if (typeof v === 'string' && v.trim() === '') v = null;
    if (v !== null && ['number', 'money', 'percent'].includes(f.type)) v = Number(v);
    out[f.name] = v;
  }
  return out;
}
